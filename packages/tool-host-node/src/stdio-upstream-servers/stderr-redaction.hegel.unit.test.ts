import { once } from 'node:events';
import { PassThrough } from 'node:stream';

import { redactCredentialText } from '@agent-collaboration/tool-engine/upstream-mcp-connectors';
import * as hegel from '@hegeldev/hegel';
import * as generators from '@hegeldev/hegel/generators';
import { StdioClientTransport } from '@modelcontextprotocol/client/stdio';
import { expect, it, vi } from 'vitest';

import { createNodeStdioUpstreamTransport } from '#node-host/stdio-upstream-servers/node-upstream-transports';

const settings = {
	testCases: 500,
	seed: 20261117,
	derandomize: true,
	database: hegel.Database.disabled,
};

function createStderrRecorder(env: Readonly<Record<string, string>>): {
	readonly transport: StdioClientTransport;
	readonly stream: PassThrough;
	readonly output: string[];
} {
	const output: string[] = [];
	const transport = createNodeStdioUpstreamTransport({
		stderr: (text): void => {
			output.push(text);
		},
	})(
		{ namespace: 'synthetic-stderr', transport: 'stdio', command: process.execPath, env },
		'stdio',
	);
	if (!(transport instanceof StdioClientTransport))
		throw new Error('Expected the real SDK transport.');
	const stream = transport.stderr;
	if (!(stream instanceof PassThrough)) throw new Error('Expected the SDK pre-start stderr pipe.');
	return { transport, stream, output };
}

async function redactStderrChunks(props: {
	readonly chunks: readonly Buffer[];
	readonly env: Readonly<Record<string, string>>;
}): Promise<string> {
	const { transport, stream, output } = createStderrRecorder(props.env);
	try {
		expect(transport.pid).toBeNull();
		const ended = once(stream, 'end');
		for (const chunk of props.chunks) stream.write(chunk);
		stream.end();
		await ended;
		return output.join('');
	} finally {
		stream.destroy();
		await transport.close();
	}
}

it('redacts an exact environment credential split across real SDK stderr chunks', async () => {
	expect(
		await redactStderrChunks({
			chunks: [Buffer.from('before opaque-cross-'), Buffer.from('boundary-secret after\n')],
			env: { SYNTHETIC_KEY: 'opaque-cross-boundary-secret' },
		}),
	).toBe('before [REDACTED] after\n');
});

it('keeps the original overlap tail after a preceding credential has already matched', async () => {
	expect(
		await redactStderrChunks({
			chunks: [Buffer.from('abcde'), Buffer.from('fghij')],
			env: { SYNTHETIC_LEFT: 'abcde', SYNTHETIC_RIGHT: 'efghij' },
		}),
	).toBe('[REDACTED]');
});

it('recognizes credential patterns split across stderr chunks', async () => {
	for (const text of ['Bearer synthetic-token', 'Basic c3ludGhldGlj', 'api_key=synthetic']) {
		expect(
			await redactStderrChunks({
				chunks: [...Buffer.from(text)].map((byte) => Buffer.from([byte])),
				env: {},
			}),
		).toBe('[REDACTED]');
	}
});

it('preserves ordinary UTF-8 characters split between byte chunks', async () => {
	const text = 'before 雪🔐 after\n';
	expect(
		await redactStderrChunks({
			chunks: [...Buffer.from(text)].map((byte) => Buffer.from([byte])),
			env: {},
		}),
	).toBe(text);
});

it('preserves word-boundary context across real SDK stderr chunks', async () => {
	for (const prefix of ['x', '_', '7', ' ', '雪']) {
		for (const suffix of ['Bearer secret', 'Basic c2VjcmV0', 'token=secret']) {
			const actual = await redactStderrChunks({
				chunks: [Buffer.from(prefix), Buffer.from(suffix)],
				env: {},
			});
			const expected = ['x', '_', '7'].includes(prefix)
				? `${prefix}${suffix}`
				: `${prefix}[REDACTED]`;
			expect(actual).toBe(expected);
			expect(actual).toBe(redactCredentialText(prefix + suffix));
		}
	}
});

it('preserves UTF-8 and exact redaction across generated byte partitions', async () => {
	await hegel.testAsync(async (tc) => {
		const secret = `synthetic-${tc.draw(
			generators.text({
				alphabet: 'abcdefghijklmnopqrstuvwxyz0123456789é雪🔐🪐',
				minSize: 4,
				maxSize: 24,
			}),
		)}🔐`;
		const bytes = Buffer.from(`before ${secret} after\n`);
		const chunks: Buffer[] = [];
		let cursor = 0;
		while (cursor < bytes.length) {
			const length = tc.draw(generators.integers({ minValue: 1, maxValue: 12 }));
			chunks.push(bytes.subarray(cursor, cursor + length));
			cursor += length;
		}
		tc.note(JSON.stringify({ secret, chunkLengths: chunks.map((chunk) => chunk.length) }));
		expect(await redactStderrChunks({ chunks, env: { SYNTHETIC_KEY: secret } })).toBe(
			'before [REDACTED] after\n',
		);
	}, settings);
});

it('delivers a complete ordinary diagnostic line before stream end', async () => {
	const { transport, stream, output } = createStderrRecorder({
		SYNTHETIC_KEY: 'a-longer-configured-secret-value-that-is-absent',
	});
	try {
		stream.write('controlled-cancelled\n');
		expect(output.join('')).toBe('controlled-cancelled\n');
	} finally {
		stream.destroy();
		await transport.close();
	}
});

it('matches batch redaction for generated UTF-8 byte partitions through the Node adapter', async () => {
	await hegel.testAsync(async (tc) => {
		const ordinary = tc.draw(
			generators.text({ alphabet: 'ab BasiCer_token=/.é雪🔐🪐', minSize: 0, maxSize: 40 }),
		);
		const secret = `opaque-${tc.draw(generators.integers({ minValue: 1000, maxValue: 999999 }))}🔐`;
		const input = `${ordinary} | Bearer Bearer token | Bearer Basic token | token=${secret} | ${secret}\n`;
		const exactValues = [secret, 'abcde', 'efghij'];
		const bytes = Buffer.from(input);
		const chunks: Buffer[] = [];
		let cursor = 0;
		while (cursor < bytes.length) {
			const length = tc.draw(generators.integers({ minValue: 1, maxValue: 16 }));
			chunks.push(bytes.subarray(cursor, cursor + length));
			cursor += length;
		}
		tc.note(JSON.stringify({ input, chunkLengths: chunks.map((chunk) => chunk.length) }));
		expect(
			await redactStderrChunks({
				chunks,
				env: Object.fromEntries(exactValues.map((value, index) => [`SYNTHETIC_${index}`, value])),
			}),
		).toBe(redactCredentialText(input, { exactValues }));
	}, settings);
});

it('flushes a pending original prefix exactly once when transport closes without stream end', async () => {
	const { transport, stream, output } = createStderrRecorder({});
	try {
		stream.write('Bearer');
		await transport.close();
		expect(output.join('')).toBe('Bearer');
		await transport.close();
		stream.destroy();
		expect(output.join('')).toBe('Bearer');
	} finally {
		stream.destroy();
		await transport.close();
	}
});

it('preserves UTF-8 exact matching after the pattern overflow cap', async () => {
	const secret = 'opaque-雪🔐-secret';
	const { transport, stream, output } = createStderrRecorder({ SYNTHETIC_KEY: secret });
	try {
		const ended = once(stream, 'end');
		stream.write(`left Bearer ${' '.repeat(4097)}`);
		expect(output.join('')).toBe('left [REDACTED]');
		for (const byte of Buffer.from(`${secret} after\n`)) stream.write(Buffer.from([byte]));
		stream.end();
		await ended;
		expect(output.join('')).toBe('left [REDACTED] after\n');
	} finally {
		stream.destroy();
		await transport.close();
	}
});

it('flushes the UTF-8 decoder on EOF without duplicating its unfinished byte sequence', async () => {
	expect(await redactStderrChunks({ chunks: [Buffer.from([0xe9])], env: {} })).toBe('\uFFFD');
});

it('flushes pending text in finally when the SDK close rejects', async () => {
	const closeError = new Error('synthetic SDK close failure');
	const closing = vi.spyOn(StdioClientTransport.prototype, 'close').mockRejectedValue(closeError);
	const { transport, stream, output } = createStderrRecorder({});
	try {
		stream.write('Bearer');
		await expect(transport.close()).rejects.toBe(closeError);
		expect(output.join('')).toBe('Bearer');
	} finally {
		stream.destroy();
		closing.mockRestore();
	}
});
